"""Derive the slot table (USB port path -> cell + rotation) from the official app's board CSS.

    python prototype/tools/gen_slots.py <app.c762092d.js.map> > app/src/slots.generated.json

The JSON is read by the UI (layout.ts) and by the engine (include_str!), so both agree.

The official app positions each module widget with `.<class>.pos<port path>` rules in pixels on a
556x814 portrait board (cells at 25 + 129*n). Their board is turned 180 degrees relative to ours:
calibrated on 2026-10-09 with the app's identify mode (numbers on the keys, an arrow on the dial,
LED colors on the knobs, live roller feedback) for keys@2-3, dial@1-3-4, knobs@1-4-3,
rollers@3-3 and faders@1-1-3 (placed by the table untouched): all five positions match the transform; keys and dial rotations match as is, the
knob and roller drawings are 180 degrees off ours, hence KIND_ROTATION_OFFSET. Only the derived
numbers are emitted, nothing of their code.
"""
import json
import re
import sys

PITCH, ORIGIN = 129.0, 25.0
GRID_COLS, GRID_ROWS = 4, 6
# official widget class -> (our kind, unrotated footprint cols x rows)
CLASSES = {
    "control-keypad": ("keys", (4, 3)),
    "roller": ("rollers", (4, 1)),
    "knob3": ("knobs", (2, 2)),
    "knobx1": ("dial", (2, 2)),
    "control-sliders5": ("faders", (4, 2)),
}
# extra clockwise degrees between their widget drawing and ours, per kind
KIND_ROTATION_OFFSET = {"keys": 0, "rollers": 180, "knobs": 180, "dial": 0, "faders": 0}
VERIFIED = {"keys@2-3", "rollers@3-3", "knobs@1-4-3", "dial@1-3-4", "faders@1-1-3"}


def rotation_of(transform: str) -> int:
    m = re.search(r"rotate\((-?\d+)deg\)", transform or "")
    return int(m.group(1)) % 360 if m else 0


def px(v):
    return float(v.replace("px", "")) if v not in (None, "0") else 0.0


def main():
    src = json.load(open(sys.argv[1], encoding="utf-8"))
    board = next(c for s, c in zip(src["sources"], src["sourcesContent"]) if s.endswith("components/Baseboard.vue"))
    style = re.sub(r"/\*.*?\*/", "", board[board.find("<style"):], flags=re.S)
    rules = {}
    for sel, body in re.findall(r"([^{}]+)\{([^}]*)\}", style):
        props = dict((k.strip(), v.strip()) for k, v in (p.split(":", 1) for p in body.split(";") if ":" in p))
        for one in sel.split(","):
            m = re.fullmatch(r"\s*\.([\w-]+)\.pos(\d+)\s*", one)
            if m and m.group(1) in CLASSES and "top" in props and "left" in props:
                rules[(m.group(1), m.group(2))] = props

    table, rejected = {}, []
    for (cls, pos), props in sorted(rules.items()):
        kind, (bc, br) = CLASSES[cls]
        rot = rotation_of(props.get("transform", ""))
        w, h = bc * PITCH - 4, br * PITCH - 4
        cx, cy = px(props["left"]) + w / 2, px(props["top"]) + h / 2
        cols, rows = (br, bc) if rot in (90, 270) else (bc, br)
        col_f = (cx - cols * PITCH / 2 - ORIGIN + 2) / PITCH
        row_f = (cy - rows * PITCH / 2 - ORIGIN + 2) / PITCH
        col, row = round(col_f), round(row_f)
        slot = "-".join(pos)
        key = f"{kind}@{slot}"
        if abs(col_f - col) > 0.3 or abs(row_f - row) > 0.3 or not (0 <= col <= GRID_COLS - cols and 0 <= row <= GRID_ROWS - rows):
            rejected.append(f"{key} (col {col_f:.2f}, row {row_f:.2f}, rot {rot})")
            continue
        # their board is turned 180 degrees relative to ours
        ours = {
            "col": GRID_COLS - cols - col,
            "row": GRID_ROWS - rows - row,
            "rotation": (rot + 180 + KIND_ROTATION_OFFSET[kind]) % 360,
        }
        table[key] = ours

    out = {
        "_comment": "Generated by prototype/tools/gen_slots.py from the official app's board layout; do not edit. "
        "kind@slot -> top-left cell and clockwise rotation on our 4x6 portrait grid.",
    }
    for key, p in table.items():
        out[key] = {**p, **({"verified": True} if key in VERIFIED else {})}
    print(json.dumps(out, indent=1))
    print(f"{len(table)} slots derived, {len(rejected)} rejected: " + "; ".join(rejected), file=sys.stderr)


if __name__ == "__main__":
    main()
