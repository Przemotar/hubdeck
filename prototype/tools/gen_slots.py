"""Derive the slot table (USB port path -> cell + rotation) from the official app's board CSS.

    python prototype/tools/gen_slots.py <app.c762092d.js.map> > app/src/slots.generated.json

The JSON is read by the UI (layout.ts) and by the engine (include_str!), so both agree.

The official app positions each module widget with `.<class>.pos<port path>` rules in pixels on a
556x814 portrait board (cells at 25 + 129*n). Their board is turned 180 degrees relative to ours:
calibrated on 2026-10-09 with the app's identify mode (numbers on the keys, an arrow on the dial,
LED colors on the knobs, live roller feedback) for keys@2-3, dial@1-3-4, knobs@1-4-3,
rollers@3-3 and faders@1-1-3 (placed by the table untouched): all five positions match the transform; keys and dial rotations match as is, the
knob and roller drawings are 180 degrees off ours, hence KIND_ROTATION_OFFSET. Only the derived
numbers are emitted, nothing of their code.
"""
import json
import re
import sys

PITCH, ORIGIN = 129.0, 25.0
GRID_COLS, GRID_ROWS = 4, 6
# official widget class -> (our kind, unrotated footprint cols x rows)
CLASSES = {
    "control-keypad": ("keys", (4, 3)),
    "roller": ("rollers", (4, 1)),
    "knob3": ("knobs", (2, 2)),
    "knobx1": ("dial", (2, 2)),
    "control-sliders5": ("faders", (4, 2)),
}
# extra clockwise degrees between their widget drawing and ours, per kind
KIND_ROTATION_OFFSET = {"keys": 0, "rollers": 180, "knobs": 180, "dial": 0, "faders": 0}
VERIFIED = {"keys@2-3", "rollers@3-3", "knobs@1-4-3", "dial@1-3-4", "faders@1-1-3"}
# moved there by the owner on 2026-10-19 (12:59-13:00, the log): the window matched his desk
VERIFIED |= {"keys@1-1-1", "keys@1-2-4", "rollers@1-1-4"}


def rotation_of(transform: str) -> int:
    m = re.search(r"rotate\((-?\d+)deg\)", transform or "")
    return int(m.group(1)) % 360 if m else 0


def px(v):
    return float(v.replace("px", "")) if v not in (None, "0") else 0.0


def main():
    src = json.load(open(sys.argv[1], encoding="utf-8"))
    board = next(c for s, c in zip(src["sources"], src["sourcesContent"]) if s.endswith("components/Baseboard.vue"))
    style = re.sub(r"/\*.*?\*/", "", board[board.find("<style"):], flags=re.S)
    rules = {}
    for sel, body in re.findall(r"([^{}]+)\{([^}]*)\}", style):
        props = dict((k.strip(), v.strip()) for k, v in (p.split(":", 1) for p in body.split(";") if ":" in p))
        for one in sel.split(","):
            m = re.fullmatch(r"\s*\.([\w-]+)\.pos(\d+)\s*", one)
            if m and m.group(1) in CLASSES and "top" in props and "left" in props:
                rules[(m.group(1), m.group(2))] = props

    table, rejected = {}, []
    for (cls, pos), props in sorted(rules.items()):
        kind, (bc, br) = CLASSES[cls]
        rot = rotation_of(props.get("transform", ""))
        w, h = bc * PITCH - 4, br * PITCH - 4
        cx, cy = px(props["left"]) + w / 2, px(props["top"]) + h / 2
        cols, rows = (br, bc) if rot in (90, 270) else (bc, br)
        col_f = (cx - cols * PITCH / 2 - ORIGIN + 2) / PITCH
        row_f = (cy - rows * PITCH / 2 - ORIGIN + 2) / PITCH
        col, row = round(col_f), round(row_f)
        slot = "-".join(pos)
        key = f"{kind}@{slot}"
        if abs(col_f - col) > 0.3 or abs(row_f - row) > 0.3 or not (0 <= col <= GRID_COLS - cols and 0 <= row <= GRID_ROWS - rows):
            rejected.append(f"{key} (col {col_f:.2f}, row {row_f:.2f}, rot {rot})")
            continue
        # their board is turned 180 degrees relative to ours
        ours = {
            "col": GRID_COLS - cols - col,
            "row": GRID_ROWS - rows - row,
            "rotation": (rot + 180 + KIND_ROTATION_OFFSET[kind]) % 360,
        }
        table[key] = ours

    derived, agree, shared = derive(table)
    if agree < shared - 4:
        sys.exit(f"the connector model matches only {agree} of {shared} known pairs: not using it")

    out = {
        "_comment": "Generated by prototype/tools/gen_slots.py from the official app's board layout; do not edit. "
        "kind@slot -> top-left cell and clockwise rotation on our 4x6 portrait grid; derived: worked out from "
        "where the connectors sit, may hang over the base's edge.",
    }
    for key, p in table.items():
        out[key] = {**p, **({"verified": True} if key in VERIFIED else {})}
    for key, p in sorted(derived.items()):
        out[key] = {**p, "derived": True, **({"verified": True} if key in VERIFIED else {})}
    print(json.dumps(out, indent=1))
    print(f"{len(table)} slots from the official app, {len(rejected)} rejected: " + "; ".join(rejected), file=sys.stderr)
    print(f"{len(derived)} derived; the connector model matches {agree} of {shared} known pairs", file=sys.stderr)


# ---------- any module in any connector (owner, 2026-10-19: "mozna wpiac panele w dowolny styk") ----------
# The official app lists 88 module-in-connector positions and leaves out those that hang over the
# base's edge (keys in 1-1-1 on a user's deck, #4). A connector is a point on the base with a
# direction; each module kind has its own connector point under it, so a position is the slot's
# point minus the module's, turned by the slot's direction. The points are fitted to the table.

FOOTPRINT = {kind: size for kind, size in CLASSES.values()}
# the reference kind for a slot's connector, most trusted first (the rollers' rotations in the
# official table disagree among themselves)
REFERENCE = ["dial", "knobs", "keys", "faders", "rollers"]


def turn(x, y, r):
    for _ in range(r // 90):
        x, y = -y, x  # clockwise on screen (y down)
    return x, y


def corner(kind, r):
    w, h = FOOTPRINT[kind]
    pts = [turn(x, y, r) for x, y in ((0, 0), (w, 0), (0, h), (w, h))]
    return min(p[0] for p in pts), min(p[1] for p in pts)


def connector(kind, point, p):
    """Where the module's connector sits on the base for a table position."""
    mx, my = corner(kind, p["rotation"])
    cx, cy = turn(point[0], point[1], p["rotation"])
    return (p["col"] + cx - mx, p["row"] + cy - my)


def candidates(kind):
    w, h = FOOTPRINT[kind]
    return [(x / 2, y / 2) for x in range(2 * w + 1) for y in range(2 * h + 1)]


def derive(table):
    by_slot = {}
    for key, p in table.items():
        kind, slot = key.split("@")
        by_slot.setdefault(slot, {})[kind] = p
    ref = REFERENCE[0]
    best = None
    for ref_point in candidates(ref):
        slots = {s: (connector(ref, ref_point, d[ref]), d[ref]["rotation"]) for s, d in by_slot.items() if ref in d}
        model, total = {ref: (ref_point, 0)}, 0
        for kind in FOOTPRINT:
            if kind == ref:
                continue
            fits = []
            for point in candidates(kind):
                for phi in (0, 90, 180, 270):
                    ok = sum(
                        1
                        for s, d in by_slot.items()
                        if kind in d and s in slots and (d[kind]["rotation"] - slots[s][1]) % 360 == phi and connector(kind, point, d[kind]) == slots[s][0]
                    )
                    fits.append((ok, point, phi))
            ok, point, phi = max(fits, key=lambda f: f[0])
            model[kind], total = (point, phi), total + ok
        if best is None or total > best[0]:
            best = (total, model)
    agree, model = best
    shared = sum(1 for d in by_slot.values() if ref in d for k in d if k != ref)
    # every slot's connector, from the most trusted module the table has there
    slot_at = {}
    for s, d in by_slot.items():
        kind = next(k for k in REFERENCE if k in d)
        point, phi = model[kind]
        slot_at[s] = (connector(kind, point, d[kind]), (d[kind]["rotation"] - phi) % 360)
    derived = {}
    for s, ((px, py), direction) in slot_at.items():
        for kind in FOOTPRINT:
            if kind in by_slot[s]:
                continue
            point, phi = model[kind]
            r = (direction + phi) % 360
            mx, my = corner(kind, r)
            cx, cy = turn(point[0], point[1], r)
            col, row = px - cx + mx, py - cy + my
            if col != int(col) or row != int(row):
                continue
            derived[f"{kind}@{s}"] = {"col": int(col), "row": int(row), "rotation": r}
    return derived, agree, shared


if __name__ == "__main__":
    main()
